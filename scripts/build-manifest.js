// Writes asset-manifest.js: every file the app needs offline, plus a version derived from their
// contents. The service worker (sw.js) imports it and caches exactly these files; because the
// version changes whenever a file changes, the browser picks up the new service worker.
//
// Usage: node scripts/build-manifest.js   (tests/manifest.test.js fails if it is out of date)

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MANIFEST = join(ROOT, "asset-manifest.js");

// What the browser loads. Not listed: sw.js and asset-manifest.js themselves (the browser
// checks them for updates on its own).
const ENTRIES = ["index.html", "manifest.webmanifest", "icons", "src", "vendor"];
const SKIP = /(^|\/)(\.|LICENSE|VERSIONS\.md$)/;

function walk(path) {
  if (!statSync(path).isDirectory()) return [path];
  return readdirSync(path).sort().flatMap((name) => walk(join(path, name)));
}

export function buildManifest() {
  const files = ENTRIES.flatMap((entry) => walk(join(ROOT, entry)))
    .map((path) => relative(ROOT, path).split(sep).join("/"))
    .filter((path) => !SKIP.test(path));
  const hash = createHash("sha256");
  for (const file of files) hash.update(file).update("\0").update(readFileSync(join(ROOT, file)));
  const version = hash.digest("hex").slice(0, 12);
  const urls = ["./", ...files.map((file) => `./${file}`)];
  return (
    "// Generated by scripts/build-manifest.js; do not edit by hand.\n" +
    `self.ASSET_MANIFEST = ${JSON.stringify({ version, urls }, null, 2)};\n`
  );
}

export function writeManifest() {
  writeFileSync(MANIFEST, buildManifest());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeManifest();
  console.log(`asset-manifest.js written`);
}
